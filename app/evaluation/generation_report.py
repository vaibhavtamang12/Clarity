"""Generation evaluation report generation (Phase 22).

Generates a markdown report with:
- Comparison table (all four configurations)
- Component contribution analysis (does each component actually help?)
- Per-category breakdown
- Methodology documentation
"""

from __future__ import annotations

from datetime import datetime, timezone

from app.evaluation.generation_runner import GenerationEvalSummary


def render_generation_evaluation_report(
    summaries: list[GenerationEvalSummary],
    *,
    dataset_name: str,
    num_questions: int,
) -> str:
    """Generate markdown report for generation evaluation."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines: list[str] = []

    lines.append("# Generation Evaluation Report (Phase 22)")
    lines.append("")
    lines.append(f"> Auto-generated by `scripts/run_generation_evaluation.py` on {now}.")
    lines.append(f"> Dataset: {dataset_name} ({num_questions} questions)")
    lines.append("")

    # ---- Methodology --------------------------------------------------------
    lines.append("## Methodology")
    lines.append("")
    lines.append("- **Evaluation**: Full RAG pipeline (retrieval + generation) run on each question")
    lines.append("- **Judge**: LLM-as-judge for semantic metrics (faithfulness, correctness, relevance)")
    lines.append("- **Citation correctness**: Reuses Phase 12 citation validation logic")
    lines.append("- **Configurations** (incremental, so we can isolate each component's contribution):")
    lines.append("  - **Baseline RAG**: Dense retrieval only")
    lines.append("  - **Hybrid RAG**: Dense + Sparse retrieval")
    lines.append("  - **Hybrid + Reranker**: Dense + Sparse + cross-encoder reranking")
    lines.append("  - **Hybrid + Reranker + Query Rewriting**: Full stack (Phase 10 transformation)")
    lines.append("- **Metrics**:")
    lines.append("  - **Faithfulness**: Are claims in the answer supported by retrieved context?")
    lines.append("  - **Answer correctness**: Does the answer match the reference answer?")
    lines.append("  - **Answer relevance**: Does the answer address the question?")
    lines.append("  - **Citation correctness**: Do citations actually support the claims?")
    lines.append("  - **Context relevance**: Is the retrieved context relevant to the question?")
    lines.append("")

    # ---- Comparison table ---------------------------------------------------
    lines.append("## Overall Results")
    lines.append("")
    lines.append("| Configuration | Faithfulness | Correctness | Relevance | Citation Correctness | Context Relevance |")
    lines.append("|---------------|--------------|-------------|-----------|---------------------|-------------------|")

    for summary in summaries:
        row = [
            summary.configuration,
            f"{summary.metrics.get('faithfulness', 0):.4f}",
            f"{summary.metrics.get('answer_correctness', 0):.4f}",
            f"{summary.metrics.get('answer_relevance', 0):.4f}",
            f"{summary.metrics.get('citation_correctness', 0):.4f}",
            f"{summary.metrics.get('context_relevance', 0):.4f}",
        ]
        lines.append("| " + " | ".join(row) + " |")

    lines.append("")

    # ---- Component contribution analysis ------------------------------------
    lines.append("## Component Contribution Analysis")
    lines.append("")
    lines.append("Does each additional component actually improve generation quality?")
    lines.append("")

    if len(summaries) >= 2:
        baseline = summaries[0]
        lines.append(f"### Baseline: {baseline.configuration}")
        lines.append("")
        lines.append(f"- Faithfulness: {baseline.metrics.get('faithfulness', 0):.4f}")
        lines.append(f"- Answer Correctness: {baseline.metrics.get('answer_correctness', 0):.4f}")
        lines.append("")

        for i, summary in enumerate(summaries[1:], start=1):
            prev = summaries[i - 1]
            faithfulness_delta = summary.metrics.get("faithfulness", 0) - prev.metrics.get("faithfulness", 0)
            correctness_delta = summary.metrics.get("answer_correctness", 0) - prev.metrics.get("answer_correctness", 0)
            relevance_delta = summary.metrics.get("answer_relevance", 0) - prev.metrics.get("answer_relevance", 0)

            lines.append(f"### Adding: {summary.configuration}")
            lines.append("")
            lines.append(f"- Faithfulness: {faithfulness_delta:+.4f} ({prev.metrics.get('faithfulness', 0):.4f} → {summary.metrics.get('faithfulness', 0):.4f})")
            lines.append(f"- Answer Correctness: {correctness_delta:+.4f} ({prev.metrics.get('answer_correctness', 0):.4f} → {summary.metrics.get('answer_correctness', 0):.4f})")
            lines.append(f"- Answer Relevance: {relevance_delta:+.4f} ({prev.metrics.get('answer_relevance', 0):.4f} → {summary.metrics.get('answer_relevance', 0):.4f})")
            lines.append("")

    # ---- Per-category breakdown ---------------------------------------------
    lines.append("## Per-Category Results")
    lines.append("")
    lines.append("### Faithfulness by Category")
    lines.append("")
    lines.append("| Category | " + " | ".join(s.configuration for s in summaries) + " |")
    lines.append("|----------|" + "|".join(["---"] * len(summaries)) + "|")

    categories = ["simple_factual", "multi_hop", "ambiguous", "unanswerable", "temporal_version", "metadata_filter"]
    for category in categories:
        row = [category]
        for summary in summaries:
            cat_metrics = summary.per_category.get(category, {})
            faithfulness = cat_metrics.get("faithfulness", 0)
            row.append(f"{faithfulness:.4f}" if faithfulness > 0 else "—")
        lines.append("| " + " | ".join(row) + " |")

    lines.append("")

    # ---- Interpretation -----------------------------------------------------
    lines.append("## Interpretation")
    lines.append("")
    lines.append("- **Faithfulness**: High faithfulness means the answer is grounded in retrieved context")
    lines.append("- **Answer correctness**: High correctness means the answer matches the reference answer")
    lines.append("- **Answer relevance**: High relevance means the answer addresses the question directly")
    lines.append("- **Citation correctness**: High citation correctness means citations actually support the claims")
    lines.append("- **Context relevance**: High context relevance means retrieval retrieved useful information")
    lines.append("")
    lines.append("### Key Insights")
    lines.append("")
    lines.append("- **Hybrid retrieval** should improve context relevance by combining semantic + lexical search")
    lines.append("- **Reranking** should improve faithfulness by refining the top-K context")
    lines.append("- **Query rewriting** should improve relevance by clarifying conversational follow-ups")
    lines.append("- **Unanswerable questions** test whether the system fabricates when evidence is absent")
    lines.append("")

    # ---- Next steps ---------------------------------------------------------
    lines.append("## Next Steps")
    lines.append("")
    lines.append("Phase 23 will measure latency and cost to determine whether the quality")
    lines.append("improvements justify the computational overhead:")
    lines.append("- p50/p95 latency per configuration")
    lines.append("- Token usage per query")
    lines.append("- Estimated cost per query")
    lines.append("")

    return "\n".join(lines)