"""Latency and cost benchmark report generation (Phase 23).

Generates a markdown report with:
- Per-stage latency table (p50/p95/p99 for each stage)
- Total latency comparison across configurations
- Token usage statistics
- Cost analysis (estimated cost per query)
- Bottleneck identification
"""

from __future__ import annotations

from datetime import datetime, timezone

from app.evaluation.latency_benchmark import LatencyBenchmarkResult


def render_latency_benchmark_report(
    results: list[LatencyBenchmarkResult],
    *,
    dataset_name: str,
    iterations: int,
) -> str:
    """Generate markdown report for latency and cost benchmark."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines: list[str] = []

    lines.append("# Latency and Cost Benchmark Report (Phase 23)")
    lines.append("")
    lines.append(f"> Auto-generated by `scripts/run_latency_benchmark.py` on {now}.")
    lines.append(f"> Dataset: {dataset_name} | Iterations per query: {iterations}")
    lines.append("")

    # ---- Methodology --------------------------------------------------------
    lines.append("## Methodology")
    lines.append("")
    lines.append("- **Benchmark**: Each question is run through the full RAG pipeline")
    lines.append(f"- **Iterations**: {iterations} measurement iterations per question (after warmup)")
    lines.append("- **Stages measured**: transform, retrieval, context, generation, total")
    lines.append("- **Percentiles**: p50 (median), p95, p99 computed across all samples")
    lines.append("- **Cost estimation**: Based on token usage × model pricing (configurable)")
    lines.append("- **Latency sources**: Real measured values, not estimates from documentation")
    lines.append("")

    # ---- Total latency comparison -------------------------------------------
    lines.append("## Total Latency Comparison")
    lines.append("")
    lines.append("| Configuration | Mean (ms) | p50 (ms) | p95 (ms) | p99 (ms) | Min (ms) | Max (ms) |")
    lines.append("|---------------|-----------|----------|----------|----------|----------|----------|")

    for result in results:
        stats = result.total_latency_stats
        row = [
            result.configuration,
            f"{stats.mean_ms:.1f}",
            f"{stats.p50_ms:.1f}",
            f"{stats.p95_ms:.1f}",
            f"{stats.p99_ms:.1f}",
            f"{stats.min_ms:.1f}",
            f"{stats.max_ms:.1f}",
        ]
        lines.append("| " + " | ".join(row) + " |")

    lines.append("")

    # ---- Per-stage latency breakdown ----------------------------------------
    lines.append("## Per-Stage Latency Breakdown")
    lines.append("")

    for result in results:
        lines.append(f"### {result.configuration}")
        lines.append("")
        lines.append("| Stage | Samples | Mean (ms) | p50 (ms) | p95 (ms) | p99 (ms) | Min (ms) | Max (ms) |")
        lines.append("|-------|---------|-----------|----------|----------|----------|----------|----------|")

        for stats in result.latency_stats:
            row = [
                stats.stage,
                str(stats.count),
                f"{stats.mean_ms:.1f}",
                f"{stats.p50_ms:.1f}",
                f"{stats.p95_ms:.1f}",
                f"{stats.p99_ms:.1f}",
                f"{stats.min_ms:.1f}",
                f"{stats.max_ms:.1f}",
            ]
            lines.append("| " + " | ".join(row) + " |")

        lines.append("")

    # ---- Token usage and cost ------------------------------------------------
    lines.append("## Token Usage and Cost Analysis")
    lines.append("")
    lines.append("| Configuration | Queries | Avg Prompt Tokens | Avg Completion Tokens | Avg Total Tokens | Total Cost (USD) | Avg Cost/Query (USD) |")
    lines.append("|---------------|---------|-------------------|----------------------|------------------|------------------|---------------------|")

    for result in results:
        token_stats = result.token_stats
        row = [
            result.configuration,
            str(token_stats.total_queries),
            f"{token_stats.avg_prompt_tokens_per_query:.1f}",
            f"{token_stats.avg_completion_tokens_per_query:.1f}",
            f"{token_stats.avg_tokens_per_query:.1f}",
            f"${token_stats.total_cost_usd:.6f}",
            f"${token_stats.avg_cost_per_query_usd:.6f}",
        ]
        lines.append("| " + " | ".join(row) + " |")

    lines.append("")

    # ---- Bottleneck identification -------------------------------------------
    lines.append("## Bottleneck Analysis")
    lines.append("")

    for result in results:
        lines.append(f"### {result.configuration}")
        lines.append("")

        # Find the slowest stage (excluding total)
        non_total_stats = [s for s in result.latency_stats if s.stage != "total"]
        if non_total_stats:
            slowest = max(non_total_stats, key=lambda s: s.p95_ms)
            lines.append(f"- **Slowest stage**: `{slowest.stage}` (p95: {slowest.p95_ms:.1f}ms)")

            # Compute percentage of total
            total_p95 = result.total_latency_stats.p95_ms
            if total_p95 > 0:
                pct = (slowest.p95_ms / total_p95) * 100
                lines.append(f"- **Bottleneck contribution**: {pct:.1f}% of total p95 latency")

        lines.append("")

    # ---- Cost optimization insights ------------------------------------------
    lines.append("## Cost Optimization Insights")
    lines.append("")

    if len(results) >= 2:
        cheapest = min(results, key=lambda r: r.token_stats.avg_cost_per_query_usd)
        most_expensive = max(results, key=lambda r: r.token_stats.avg_cost_per_query_usd)

        lines.append(f"- **Cheapest configuration**: `{cheapest.configuration}` (${cheapest.token_stats.avg_cost_per_query_usd:.6f}/query)")
        lines.append(f"- **Most expensive configuration**: `{most_expensive.configuration}` (${most_expensive.token_stats.avg_cost_per_query_usd:.6f}/query)")

        cost_ratio = most_expensive.token_stats.avg_cost_per_query_usd / max(cheapest.token_stats.avg_cost_per_query_usd, 0.000001)
        lines.append(f"- **Cost ratio**: {cost_ratio:.2f}x (most expensive / cheapest)")

    lines.append("")

    # ---- Next steps -----------------------------------------------------------
    lines.append("## Next Steps")
    lines.append("")
    lines.append("Phase 29 will use this benchmark data to:")
    lines.append("- Identify optimization opportunities (embedding batching, caching, context size)")
    lines.append("- Profile the complete system under production-like load")
    lines.append("- Document before/after performance for each optimization")
    lines.append("")

    return "\n".join(lines)