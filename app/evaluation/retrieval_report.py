"""Retrieval evaluation report generation (Phase 21).

Generates a markdown report with:
- Comparison table (all four retriever configurations)
- Per-category breakdown
- Analysis of which configuration performs best
- Methodology documentation
"""

from __future__ import annotations

from datetime import datetime, timezone

from app.evaluation.retrieval_runner import RetrievalEvalSummary


def render_retrieval_evaluation_report(
    summaries: list[RetrievalEvalSummary],
    *,
    dataset_name: str,
    num_questions: int,
) -> str:
    """Generate markdown report for retrieval evaluation."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines: list[str] = []

    lines.append("# Retrieval Evaluation Report (Phase 21)")
    lines.append("")
    lines.append(f"> Auto-generated by `scripts/run_retrieval_evaluation.py` on {now}.")
    lines.append(f"> Dataset: {dataset_name} ({num_questions} questions)")
    lines.append("")

    # ---- Methodology --------------------------------------------------------
    lines.append("## Methodology")
    lines.append("")
    lines.append("- **Dataset**: Evaluation corpus with 10+ documents, 50+ gold questions")
    lines.append("- **Question taxonomy**: simple_factual, multi_hop, ambiguous, unanswerable, temporal_version, metadata_filter")
    lines.append("- **Gold evidence**: Verbatim spans from corpus documents (strategy-agnostic)")
    lines.append("- **Retrievers evaluated**:")
    lines.append("  - **Dense**: Real embeddings (bge-m3) + Qdrant vector similarity")
    lines.append("  - **Sparse**: PostgreSQL tsvector + GIN index (BM25-style ranking)")
    lines.append("  - **Hybrid**: Dense + Sparse with Reciprocal Rank Fusion")
    lines.append("  - **Hybrid + Reranker**: Hybrid retrieval + cross-encoder reranking (bge-reranker-v2-m3)")
    lines.append("- **Metrics**: Recall@K, Precision@K, MRR, Hit Rate (K ∈ {5, 10, 20})")
    lines.append("- **Evidence matching**: Containment or ≥0.7 token overlap (Phase 5 methodology)")
    lines.append("")

    # ---- Comparison table ---------------------------------------------------
    lines.append("## Overall Results")
    lines.append("")
    lines.append("| Retriever | MRR | Recall@5 | Recall@10 | Recall@20 | Precision@5 | Precision@10 | Hit@10 |")
    lines.append("|-----------|-----|----------|-----------|-----------|-------------|--------------|--------|")

    for summary in summaries:
        row = [
            summary.retriever_name,
            f"{summary.metrics.get('mrr', 0):.4f}",
            f"{summary.metrics.get('recall_at_5', 0):.4f}",
            f"{summary.metrics.get('recall_at_10', 0):.4f}",
            f"{summary.metrics.get('recall_at_20', 0):.4f}",
            f"{summary.metrics.get('precision_at_5', 0):.4f}",
            f"{summary.metrics.get('precision_at_10', 0):.4f}",
            f"{summary.metrics.get('hit_rate_at_10', 0):.4f}",
        ]
        lines.append("| " + " | ".join(row) + " |")

    lines.append("")

    # ---- Per-category breakdown ---------------------------------------------
    lines.append("## Per-Category Results")
    lines.append("")
    lines.append("### Recall@10 by Category")
    lines.append("")
    lines.append("| Category | Dense | Sparse | Hybrid | Hybrid+Reranker |")
    lines.append("|----------|-------|--------|--------|-----------------|")

    categories = ["simple_factual", "multi_hop", "ambiguous", "unanswerable", "temporal_version", "metadata_filter"]
    for category in categories:
        row = [category]
        for summary in summaries:
            cat_metrics = summary.per_category.get(category, {})
            recall_10 = cat_metrics.get("recall_at_10", 0)
            row.append(f"{recall_10:.4f}" if recall_10 > 0 else "—")
        lines.append("| " + " | ".join(row) + " |")

    lines.append("")

    # ---- Analysis -----------------------------------------------------------
    lines.append("## Analysis")
    lines.append("")

    if summaries:
        best_mrr = max(summaries, key=lambda s: s.metrics.get("mrr", 0))
        best_recall = max(summaries, key=lambda s: s.metrics.get("recall_at_10", 0))
        best_precision = max(summaries, key=lambda s: s.metrics.get("precision_at_5", 0))

        lines.append("### Best Performers")
        lines.append("")
        lines.append(f"- **Best MRR**: {best_mrr.retriever_name} ({best_mrr.metrics.get('mrr', 0):.4f})")
        lines.append(f"- **Best Recall@10**: {best_recall.retriever_name} ({best_recall.metrics.get('recall_at_10', 0):.4f})")
        lines.append(f"- **Best Precision@5**: {best_precision.retriever_name} ({best_precision.metrics.get('precision_at_5', 0):.4f})")
        lines.append("")

        # Component contribution analysis
        dense = next((s for s in summaries if s.retriever_name == "dense"), None)
        sparse = next((s for s in summaries if s.retriever_name == "sparse"), None)
        hybrid = next((s for s in summaries if s.retriever_name == "hybrid"), None)
        reranked = next((s for s in summaries if s.retriever_name == "hybrid_reranker"), None)

        if dense and sparse and hybrid:
            lines.append("### Component Contributions")
            lines.append("")
            hybrid_recall = hybrid.metrics.get("recall_at_10", 0)
            dense_recall = dense.metrics.get("recall_at_10", 0)
            sparse_recall = sparse.metrics.get("recall_at_10", 0)
            baseline = max(dense_recall, sparse_recall)
            improvement = hybrid_recall - baseline
            lines.append(
                f"- **Hybrid vs best single retriever**: {improvement:+.4f} Recall@10 "
                f"(hybrid={hybrid_recall:.4f}, baseline={baseline:.4f})"
            )

            if reranked:
                reranker_improvement = reranked.metrics.get("recall_at_10", 0) - hybrid_recall
                lines.append(
                    f"- **Reranker contribution**: {reranker_improvement:+.4f} Recall@10 "
                    f"(reranked={reranked.metrics.get('recall_at_10', 0):.4f}, hybrid={hybrid_recall:.4f})"
                )
            lines.append("")

    # ---- Interpretation -----------------------------------------------------
    lines.append("## Interpretation")
    lines.append("")
    lines.append("- **Dense retrieval** captures semantic similarity but may miss exact keyword matches")
    lines.append("- **Sparse retrieval** (BM25) excels at exact matches but lacks semantic understanding")
    lines.append("- **Hybrid retrieval** combines both strengths via Reciprocal Rank Fusion")
    lines.append("- **Reranking** refines the top-K results using a cross-encoder for higher precision")
    lines.append("- **Unanswerable questions** test whether the system retrieves irrelevant content (lower recall is acceptable)")
    lines.append("")

    # ---- Next steps ---------------------------------------------------------
    lines.append("## Next Steps")
    lines.append("")
    lines.append("Phase 22 will evaluate whether better retrieval translates to better answers:")
    lines.append("- Faithfulness (grounding)")
    lines.append("- Answer correctness")
    lines.append("- Citation correctness")
    lines.append("")

    return "\n".join(lines)